// Regenerates server/routes.js from the files in server/ (run automatically before every build).
// File name → URL:  rooms/[code].js → /api/rooms/:code ;  rooms/index.js → /api/rooms
import { readdirSync, statSync, writeFileSync } from "node:fs";
import path from "node:path";

const ROOT = path.resolve("server");
const files = [];
(function walk(dir) {
  for (const name of readdirSync(dir)) {
    const full = path.join(dir, name);
    if (statSync(full).isDirectory()) { if (name !== "_lib") walk(full); }
    else if (name.endsWith(".js") && name !== "routes.js") files.push(path.relative(ROOT, full).slice(0, -3));
  }
})(ROOT);

const routes = files
  .map((rel) => ({ rel, pattern: rel.replace(/\[(\w+)\]/g, ":$1").replace(/(^|\/)index$/, "") }))
  .sort((a, b) => (a.pattern.split(":").length - b.pattern.split(":").length) || a.pattern.localeCompare(b.pattern)); // static before :params

const out = `// GENERATED by scripts/gen-routes.mjs — do not edit. Run \`npm run gen:routes\` after adding a handler.
// Route table for the single /api function (Vercel's Hobby plan allows only 12 functions,
// so every handler is bundled behind one function in api/index.js). ":name" segments become req.query.name.
${routes.map((r, i) => `import h${i} from "./${r.rel}.js";`).join("\n")}

const ROUTES = [
${routes.map((r, i) => `  ["${r.pattern}", h${i}],`).join("\n")}
].map(([pattern, handler]) => ({ segs: pattern.split("/"), handler }));

/** Finds the handler for "rooms/ABC123" → { handler, params: { code: "ABC123" } }. */
export function match(pathname) {
  const parts = pathname.split("/").filter(Boolean);
  for (const { segs, handler } of ROUTES) {
    if (segs.length !== parts.length) continue;
    const params = {};
    const ok = segs.every((s, i) => (s.startsWith(":") ? ((params[s.slice(1)] = decodeURIComponent(parts[i])), true) : s === parts[i]));
    if (ok) return { handler, params };
  }
  return null;
}
`;
writeFileSync(path.join(ROOT, "routes.js"), out);
console.log(`routes.js: ${routes.length} routes`);
